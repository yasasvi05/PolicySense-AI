
"""Orchestrates assistant queries across banking and insurance."""

import time

from sqlalchemy.orm import Session

from .. import models
from . import generator, retriever


def answer_query(
    db: Session,
    user: models.User,
    message: str,
    focus,
    domain: str | None = None,
) -> dict:
    trace = []
    t0 = time.perf_counter()

    # The authenticated user's domain is authoritative.
    domain = user.domain or "insurance"

    if domain not in {"banking", "insurance"}:
        domain = "insurance"

    # Select the customer ID associated with this user's domain.
    customer_id = (
        user.bank_customer_id
        if domain == "banking"
        else user.customer_id
    )

    # Retrieve customer-specific information.
    ctx = retriever.customer_context(
        db,
        customer_id,
        message,
        focus,
        domain=domain,
    )

    trace.append({
        "step": "FastAPI",
        "status": "ok",
        "detail": f"Domain: {domain}; intent: {ctx['intent']}",
    })

    trace.append({
        "step": "Database",
        "status": "ok" if ctx["record"] else "empty",
        "detail": f"{len(ctx['highlights'])} customer facts retrieved",
    })

    # Retrieve relevant policy documents for the selected domain.
    chunks, retrieval = retriever.policy_chunks(
        db,
        message,
        ctx["intent"],
        domain=domain,
    )

    trace.append({
        "step": "ChromaDB",
        "status": "ok" if chunks else "empty",
        "detail": f"{len(chunks)} {domain} clauses via {retrieval}",
    })

    # Generate an answer using the retrieved customer and policy context.
    answer, generation = generator.generate(
        message,
        ctx["intent"],
        ctx["record"],
        chunks,
        domain=domain,
    )

    trace.append({
        "step": "LangChain",
        "status": "ok",
        "detail": "Prompt assembled from retrieved sources",
    })

    trace.append({
        "step": "Gemini LLM",
        "status": "ok" if generation == "gemini" else "fallback",
        "detail": (
            "Generated by Gemini"
            if generation == "gemini"
            else "No API key or generation failed; fallback answer used"
        ),
    })

    # Collect sources returned to the frontend.
    sources = {
        "customer_sources": ctx["highlights"],
        "customer_record": ctx["record"],
        "policy_sources": chunks,
    }

    # Save the query and answer in the database.
    log = models.QueryLog(
        user_id=user.id,
        domain=domain,
        customer_id=customer_id,
        query=message,
        intent=ctx["intent"],
        answer=answer,
        sources=sources,
        generation=generation,
    )

    db.add(log)
    db.commit()
    db.refresh(log)

    return {
        "query_id": log.id,
        "domain": domain,
        "answer": answer,
        "intent": ctx["intent"],
        "generation": generation,
        "retrieval": retrieval,
        "mode": (
            "live"
            if generation == "gemini" and retrieval == "chromadb"
            else "degraded"
        ),
        "grounded": bool(ctx["record"] or chunks),
        **sources,
        "pipeline": trace,
        "latency_ms": int(
            (time.perf_counter() - t0) * 1000
        ),
    }
